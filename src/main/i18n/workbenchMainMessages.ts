const messages: Record<AppLocale, Record<WorkbenchMainMessageKey, string>> = {
  'zh-CN': zhCN,
  'en-US': enUS,
}

/** 两张表本身：测试拿它核对两种语言的占位符对得上。 */
export const workbenchMainMessageTables: Readonly<
  Record<AppLocale, Readonly<Record<string, string>>>
> = messages

export function workbenchMainText(
  key: WorkbenchMainMessageKey,
  params?: Readonly<Record<string, string | number>>
): string {
  return workbenchMainTextIn(getWorkbenchMainLocale(), key, params)
}

/**
 * 按指定的语言出文字，不看 main 进程此刻的界面语言。给写进用户仓库里的内容用（没写说明时代拟的提交说明）：
 * 它按发起请求的界面带来的语言写。
 */
export function workbenchMainTextIn(
  locale: AppLocale,
  key: WorkbenchMainMessageKey,
  params?: Readonly<Record<string, string | number>>
): string {
  const template = messages[locale][key]
  return params
    ? template.replace(/\{(\w+)\}/gu, (placeholder, name: string) =>
        params[name] === undefined ? placeholder : String(params[name])
      )
    : template
}
