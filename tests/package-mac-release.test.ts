import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { mkdtemp, readFile, rm, stat, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import path from 'node:path'

import { describe, test } from 'bun:test'

import {
  buildElectronBuilderArgs,
  discoverCurrentMacDmg,
  finalizeDmgUpdateMetadata,
  hasCompleteNotarizationCredentials,
  resolveMacOutputDirectory,
  resolveMacPackagingEnvironment,
  resolveNotarizationCredentials,
  runMacPackage,
  selectCurrentMacDmg,
  snapshotCurrentMacDmgs,
} from '../scripts/release/packageMac.mjs'

const requireFromTest = createRequire(import.meta.url)
const { JSON_SCHEMA, load: parseYaml } = requireFromTest('js-yaml')

void describe('Workbench macOS release packaging', () => {
  void test('uses the saved local notarization profile without reading Keychain contents', () => {
    const environment = resolveMacPackagingEnvironment({ PATH: '/usr/bin' })

    assert.equal(environment.APPLE_KEYCHAIN_PROFILE, 'velaros-notary')
    assert.equal(environment.PATH, '/usr/bin')
  })

  void test('preserves configured CI and custom notarization credentials', () => {
    const ciCredentials = {
      APPLE_ID: 'release@example.com',
      APPLE_APP_SPECIFIC_PASSWORD: 'secret',
      APPLE_TEAM_ID: 'TEAM',
    }
    const customProfile = { APPLE_KEYCHAIN_PROFILE: ' custom-profile ' }

    assert.equal(hasCompleteNotarizationCredentials(ciCredentials), true)
    assert.deepEqual(resolveMacPackagingEnvironment(ciCredentials), ciCredentials)
    assert.deepEqual(resolveMacPackagingEnvironment(customProfile), {
      APPLE_KEYCHAIN_PROFILE: 'custom-profile',
    })
  })

  void test('maps all supported credential strategies for @electron/notarize', () => {
    assert.deepEqual(resolveNotarizationCredentials({}), {
      tool: 'notarytool',
      keychainProfile: 'velaros-notary',
    })
    assert.deepEqual(
      resolveNotarizationCredentials({
        APPLE_KEYCHAIN_PROFILE: ' custom-profile ',
        APPLE_KEYCHAIN: ' login.keychain-db ',
      }),
      {
        tool: 'notarytool',
        keychainProfile: 'custom-profile',
        keychain: 'login.keychain-db',
      }
    )
    assert.deepEqual(
      resolveNotarizationCredentials({
        APPLE_ID: ' release@example.com ',
        APPLE_APP_SPECIFIC_PASSWORD: ' password ',
        APPLE_TEAM_ID: ' TEAM ',
      }),
      {
        tool: 'notarytool',
        appleId: 'release@example.com',
        appleIdPassword: 'password',
        teamId: 'TEAM',
      }
    )
    assert.deepEqual(
      resolveNotarizationCredentials({
        APPLE_API_KEY: ' /tmp/AuthKey.p8 ',
        APPLE_API_KEY_ID: ' KEY ',
        APPLE_API_ISSUER: ' ISSUER ',
      }),
      {
        tool: 'notarytool',
        appleApiKey: '/tmp/AuthKey.p8',
        appleApiKeyId: 'KEY',
        appleApiIssuer: 'ISSUER',
      }
    )
    assert.throws(
      () => resolveNotarizationCredentials({ APPLE_ID: 'release@example.com' }),
      /credentials are incomplete/u
    )
  })

  void test('resolves default, inline, and separated output directory options', () => {
    const rootDirectory = '/repo'

    assert.equal(resolveMacOutputDirectory([], { rootDirectory }), '/repo/artifacts/desktop')
    assert.equal(
      resolveMacOutputDirectory(['-c.directories.output=artifacts/local'], { rootDirectory }),
      '/repo/artifacts/local'
    )
    assert.equal(
      resolveMacOutputDirectory(
        ['--', '--config.directories.output', '/tmp/workbench-output'],
        { rootDirectory }
      ),
      '/tmp/workbench-output'
    )
    assert.throws(
      () =>
        resolveMacOutputDirectory(
          [
            '-c.directories.output=artifacts/first',
            '--config.directories.output=artifacts/second',
          ],
          { rootDirectory }
        ),
      /conflicting output directory/u
    )
  })

  void test('selects only the unique current-version macOS DMG', () => {
    assert.equal(
      selectCurrentMacDmg(
        [
          'VelarOS-Workbench-0.3.28-mac-arm64.dmg',
          'VelarOS-Workbench-0.3.29-mac-arm64.dmg',
          'VelarOS-Workbench-0.3.29-mac-arm64.dmg.blockmap',
        ],
        '0.3.29'
      ),
      'VelarOS-Workbench-0.3.29-mac-arm64.dmg'
    )
    assert.throws(
      () => selectCurrentMacDmg([], '0.3.29'),
      /No macOS DMG/u
    )
    assert.throws(
      () =>
        selectCurrentMacDmg(
          [
            'VelarOS-Workbench-0.3.29-mac-arm64.dmg',
            'VelarOS-Workbench-0.3.29-mac-x64.dmg',
          ],
          '0.3.29'
        ),
      /Multiple macOS DMGs/u
    )
  })

  void test('requires the current-version DMG to be generated by this build', async () => {
    const fileName = 'VelarOS-Workbench-0.3.29-mac-arm64.dmg'
    const fileEntry = { name: fileName, isFile: () => true }
    const before = await snapshotCurrentMacDmgs({
      outputDirectory: '/output',
      version: '0.3.29',
      readDirectory: async () => [fileEntry],
      readStat: async () => ({ dev: 1, ino: 2, size: 3, mtimeMs: 4, ctimeMs: 5 }),
    })
    const after = await snapshotCurrentMacDmgs({
      outputDirectory: '/output',
      version: '0.3.29',
      readDirectory: async () => [fileEntry],
      readStat: async () => ({ dev: 1, ino: 2, size: 6, mtimeMs: 7, ctimeMs: 8 }),
    })

    assert.equal(
      await discoverCurrentMacDmg({
        outputDirectory: '/output',
        version: '0.3.29',
        previousArtifacts: before,
        snapshotDmgs: async () => after,
      }),
      `/output/${fileName}`
    )
    await assert.rejects(
      discoverCurrentMacDmg({
        outputDirectory: '/output',
        version: '0.3.29',
        previousArtifacts: before,
        snapshotDmgs: async () => before,
      }),
      /No macOS DMG/u
    )
  })

  void test('builds, discovers, then notarizes and staples the generated DMG', async () => {
    const calls: string[] = []
    const outputDirectory = '/repo/artifacts/local'
    const dmgPath = `${outputDirectory}/VelarOS-Workbench-0.3.29-mac-arm64.dmg`

    const result = await runMacPackage({
      args: [`-c.directories.output=${outputDirectory}`],
      environment: { APPLE_KEYCHAIN_PROFILE: 'test-profile' },
      platform: 'darwin',
      version: '0.3.29',
      snapshotDmgs: async () => {
        calls.push('snapshot')
        return []
      },
      runBuilder: async ({ builderArgs }: { builderArgs: string[] }) => {
        calls.push(`build:${builderArgs.at(-1)}`)
      },
      discoverDmg: async (options: {
        outputDirectory: string
        previousArtifacts: unknown[]
        version: string
      }) => {
        assert.deepEqual(options.previousArtifacts, [])
        calls.push(`discover:${options.outputDirectory}:${options.version}`)
        return dmgPath
      },
      notarizeDmg: async (options: {
        appPath: string
        keychainProfile: string
        tool: string
      }) => {
        calls.push(
          `notarize:${options.appPath}:${options.tool}:${options.keychainProfile}`
        )
      },
      verifyDmgSignature: async (path: string) => {
        calls.push(`verify-signed:${path}`)
      },
      verifyDmgNotarization: async (path: string) => {
        calls.push(`verify-notarized:${path}`)
      },
      finalizeDmgMetadata: async (path: string) => {
        calls.push(`finalize-metadata:${path}`)
      },
    })

    assert.deepEqual(calls, [
      'snapshot',
      'build:never',
      'discover:/repo/artifacts/local:0.3.29',
      `verify-signed:${dmgPath}`,
      `notarize:${dmgPath}:notarytool:test-profile`,
      `verify-notarized:${dmgPath}`,
      `finalize-metadata:${dmgPath}`,
    ])
    assert.deepEqual(result, { dmgPath, outputDirectory, version: '0.3.29' })
  })

  void test('regenerates DMG blockmap and update identity after stapling', async () => {
    const root = await mkdtemp(path.join(tmpdir(), 'workbench-mac-metadata-'))
    const dmgName = 'VelarOS-Workbench-0.3.29-mac-arm64.dmg'
    const dmgPath = path.join(root, dmgName)
    const blockmapPath = `${dmgPath}.blockmap`
    const metadataPath = path.join(root, 'latest-mac.yml')
    const zipSha512 = 'zip-sha512-is-preserved'
    const dmgBody = Buffer.from('final signed, notarized, and stapled DMG fixture')

    try {
      await Promise.all([
        writeFile(dmgPath, dmgBody),
        writeFile(blockmapPath, 'stale-blockmap'),
        writeFile(
          metadataPath,
          [
            'version: 0.3.29',
            'files:',
            '  - url: VelarOS-Workbench-0.3.29-mac-arm64.zip',
            `    sha512: ${zipSha512}`,
            '    size: 10',
            `  - url: ${dmgName}`,
            '    sha512: stale-dmg-sha512',
            '    size: 1',
            'path: VelarOS-Workbench-0.3.29-mac-arm64.zip',
            `sha512: ${zipSha512}`,
            '',
          ].join('\n')
        ),
      ])

      const result = await finalizeDmgUpdateMetadata(dmgPath)
      const expectedSha512 = createHash('sha512').update(dmgBody).digest('base64')
      const metadata = parseYaml(await readFile(metadataPath, 'utf8'), {
        schema: JSON_SCHEMA,
      }) as {
        files: Array<{ url: string; sha512: string; size: number }>
        path: string
        sha512: string
      }
      const dmgRecord = metadata.files.find((entry) => entry.url === dmgName)

      assert.equal(result.size, dmgBody.length)
      assert.equal(result.sha512, expectedSha512)
      assert.deepEqual(dmgRecord, {
        url: dmgName,
        sha512: expectedSha512,
        size: dmgBody.length,
      })
      assert.equal(metadata.path, 'VelarOS-Workbench-0.3.29-mac-arm64.zip')
      assert.equal(metadata.sha512, zipSha512)
      assert.ok((await stat(blockmapPath)).size > 0)
      assert.notEqual(await readFile(blockmapPath, 'utf8'), 'stale-blockmap')
    } finally {
      await rm(root, { recursive: true, force: true })
    }
  })

  void test('contains no credential-reading preflight', () => {
    const source = readFileSync(new URL('../scripts/release/packageMac.mjs', import.meta.url), 'utf8')

    assert.doesNotMatch(source, /find-generic-password|notarytool[\s\S]+history/u)
  })

  void test('requires signed macOS applications and disk images', () => {
    const builderConfig = readFileSync(
      new URL('../electron-builder.yml', import.meta.url),
      'utf8'
    )

    assert.match(builderConfig, /\nmac:\n[\s\S]*?\n {2}forceCodeSigning: true\n/u)
    assert.match(builderConfig, /\ndmg:\n {2}sign: true\n/u)
  })

  void test('always disables electron-builder implicit publishing', () => {
    assert.deepEqual(buildElectronBuilderArgs([]), [
      '--config',
      'electron-builder.yml',
      '--mac',
      '--publish',
      'never',
    ])
    assert.deepEqual(buildElectronBuilderArgs(['--', '--publish', 'never']), [
      '--config',
      'electron-builder.yml',
      '--mac',
      '--publish',
      'never',
    ])
    assert.deepEqual(buildElectronBuilderArgs(['--publish=never', '-p', 'never']), [
      '--config',
      'electron-builder.yml',
      '--mac',
      '--publish',
      'never',
    ])
    assert.throws(
      () => buildElectronBuilderArgs(['--publish', 'always']),
      /publishing disabled/u
    )
    assert.throws(
      () => buildElectronBuilderArgs(['--publish', 'never', '-p=always']),
      /publishing disabled/u
    )
  })
})
